#!/usr/bin/env bash
# Rebuild f3-bundle.tar.gz reproducibly from this repo (needs its git history for the two pinned PROTOCOL.md versions).
# Same inputs + same Python/zlib => same bytes. Usage: docs/f3/bundle/make_bundle.sh [OUT_DIR]   (default OUT_DIR: docs/f3)
# Copies only; nothing in the repo is modified. Does not run any GPU job or contact any network.
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
OUT="${1:-$REPO/docs/f3}"
mkdir -p "$OUT"
exec python3 -I - "$REPO" "$OUT" <<'PY'
import gzip, hashlib, io, os, subprocess, sys, tarfile
from pathlib import Path

repo, out = Path(sys.argv[1]), Path(sys.argv[2])
P1_PROTO, P2_PROTO = "0908479", "0bb8968"   # commits whose docs/f3/PROTOCOL.md hash equals each genesis pin (checked below)
PINS = {"pilot1": "583fabc7caaa9d97defa6da8cb3b2baeb8497be9f5950cc56762325de1c0a69e",
        "pilot2": "e7c3871a022dbde4258895f246aae44594a09bd5122991a0f42cc4fc166739c8"}
sha = lambda b: hashlib.sha256(b).hexdigest()
files = {}      # tar path -> (bytes, origin)

def add(path, data, origin):
    assert path not in files, path
    files[path] = (data, origin)

def git_show(commit, path):
    return subprocess.run(["git", "show", f"{commit}:{path}"], cwd=repo, capture_output=True, check=True).stdout

def copy_tree(src_rel, dst, skip=("__pycache__", "tests", ".pyc")):
    for p in sorted((repo / src_rel).rglob("*")):
        if p.is_file() and not any(s in p.parts or p.name.endswith(".pyc") for s in skip):
            add(f"{dst}/{p.relative_to(repo / src_rel).as_posix()}", p.read_bytes(), f"{src_rel}/{p.relative_to(repo / src_rel).as_posix()}")

# 1. verifier and pinned code (the genesis receipts pin these hashes)
copy_tree("challenge/f3", "challenge/f3")
# 2. the PROTOCOL.md versions the two genesis receipts pin, taken from git history, and the current file
for name, c in (("pilot1", P1_PROTO), ("pilot2", P2_PROTO)):
    b = git_show(c, "docs/f3/PROTOCOL.md")
    assert sha(b) == PINS[name], f"{name}: PROTOCOL.md at {c} does not hash to the pin"
    add(f"protocol/PROTOCOL.{name}.md", b, f"git show {c}:docs/f3/PROTOCOL.md")
add("protocol/PROTOCOL.current.md", (repo / "docs/f3/PROTOCOL.md").read_bytes(), "docs/f3/PROTOCOL.md (working tree; adds A5 and later text)")
# 3. runs, copied verbatim
copy_tree("docs/f3/pilot", "runs/pilot1")
copy_tree("docs/f3/smoke_p2", "runs/smoke_p2")
for f in ("README.md", "PINNED.txt", "host.pub", "arm.log", "verify2.txt", "replay2.txt"):
    add(f"runs/pilot2/{f}", (repo / "docs/f3/pilot2" / f).read_bytes(), f"docs/f3/pilot2/{f}")
tgz = (repo / "docs/f3/pilot2/p2out.tgz").read_bytes()
add("runs/pilot2/P2OUT_TGZ_SHA256.txt", (sha(tgz) + "  p2out.tgz\n").encode(), "sha256 of docs/f3/pilot2/p2out.tgz, from which the files below were extracted unchanged")
with tarfile.open(fileobj=io.BytesIO(tgz)) as t:
    for m in t.getmembers():
        if m.isfile() and "__pycache__" not in m.name and not m.name.endswith(".pyc"):
            data, dst = t.extractfile(m).read(), f"runs/pilot2/{m.name}"
            if dst in files:   # host.pub is in both places: they must be identical
                assert files[dst][0] == data, f"{dst} differs between pilot2/ and p2out.tgz"
            else:
                add(dst, data, f"docs/f3/pilot2/p2out.tgz:{m.name}")
# 4. reviewer-facing files
for f in ("README.md", "REVIEW_TEMPLATE.md", "check.sh", "make_bundle.sh", "TIER_A_OUTPUT.txt"):
    p = repo / "docs/f3/bundle" / f
    if p.exists():
        add(f, p.read_bytes(), f"docs/f3/bundle/{f}")

man = ["# Manifest: every file, where it came from, its SHA-256\n", "", "| path | origin | sha256 |", "|---|---|---|"]
for k in sorted(files):
    man.append(f"| `{k}` | {files[k][1]} | `{sha(files[k][0])}` |")
add("MANIFEST.md", ("\n".join(man) + "\n").encode(), "generated by make_bundle.sh")
sums = "".join(f"{sha(files[k][0])}  {k}\n" for k in sorted(files))
add("SHA256SUMS", sums.encode(), "generated by make_bundle.sh (covers every other file)")

raw = io.BytesIO()
with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0, compresslevel=9, filename="") as gz:
    with tarfile.open(fileobj=gz, mode="w", format=tarfile.PAX_FORMAT) as t:
        for k in sorted(files):
            ti = tarfile.TarInfo(f"f3-bundle/{k}")
            ti.size, ti.mtime, ti.uid, ti.gid, ti.uname, ti.gname = len(files[k][0]), 0, 0, 0, "", ""
            ti.mode = 0o755 if k.endswith(".sh") else 0o644
            t.addfile(ti, io.BytesIO(files[k][0]))
dst = out / "f3-bundle.tar.gz"
dst.write_bytes(raw.getvalue())
(out / "f3-bundle.tar.gz.sha256").write_text(f"{sha(raw.getvalue())}  f3-bundle.tar.gz\n")
print(f"{dst}\n{sha(raw.getvalue())}  ({len(files)} files)")
PY
